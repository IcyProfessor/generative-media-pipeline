from typing import Protocol
from ..assets.manifest import Catalog
from ..models import Script, Transcript, Timing, VisualPlan, ScenePlan
from ..providers.base import Prompt


class Recipe(Protocol):
    """Format policy. No network, filesystem writes, or orchestration here."""
    name: str
    version: int

    def validate_catalog(self, catalog: Catalog) -> None: ...
    def script_prompt(self, catalog: Catalog, seed: int) -> Prompt: ...
    def fixture_script(self, catalog: Catalog, seed: int) -> Script: ...
    def validate_script(self, script: Script, catalog: Catalog) -> None: ...
    def timeline(self, script: Script, transcript: Transcript, duration: float, catalog: Catalog) -> list[Timing]: ...
    def visual_prompt(self, catalog: Catalog, script: Script, transcript: Transcript) -> Prompt: ...
    def fixture_visuals(self, catalog: Catalog, script: Script) -> VisualPlan: ...
    def compile_plan(self, script: Script, visuals: VisualPlan, timing: list[Timing], catalog: Catalog, duration: float) -> ScenePlan: ...
