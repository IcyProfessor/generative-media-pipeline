"""Build original geometric test assets. No external images or font files needed."""
from pathlib import Path
import json
from PIL import Image, ImageDraw


def draw_object(obj: str) -> Image.Image:
    im = Image.new("RGBA", (220, 220))
    d = ImageDraw.Draw(im)
    if obj == "apple":
        d.ellipse((35, 66, 125, 183), fill="#EF6351")
        d.ellipse((92, 66, 184, 183), fill="#EF6351")
        d.line((109, 83, 116, 35), fill="#684634", width=10)
        d.ellipse((118, 31, 171, 56), fill="#65A765")
    elif obj == "balloon":
        d.ellipse((53, 19, 172, 162), fill="#EA82B2")
        d.polygon([(108, 156), (99, 170), (120, 170)], fill="#D55F96")
        d.line([(109, 170), (119, 187), (105, 209)], fill="#5C5570", width=3)
    elif obj == "cloud":
        for box in [(22, 89, 103, 165), (61, 50, 154, 165), (117, 81, 201, 165)]:
            d.ellipse(box, fill="#F5FAFF", outline="#769BB4", width=3)
        d.rectangle((60, 117, 169, 163), fill="#F5FAFF")
    elif obj == "diamond":
        d.polygon([(110, 18), (194, 105), (110, 204), (26, 105)], fill="#71CFDC", outline="#266D91", width=5)
        d.line([(110, 18), (90, 104), (110, 204)], fill="#DEF8FF", width=7)
        d.line([(26, 105), (194, 105)], fill="#DEF8FF", width=7)
    elif obj == "egg":
        d.ellipse((48, 28, 173, 197), fill="#FFE7B8", outline="#BA9170", width=4)
        d.arc((68, 48, 148, 165), 130, 245, fill="#FFFFFF", width=7)
    else:
        d.polygon([(160, 100), (212, 54), (212, 163)], fill="#FFB653")
        d.ellipse((19, 61, 184, 161), fill="#EF974A")
        d.ellipse((47, 88, 65, 106), fill="#FFFFFF")
        d.ellipse((54, 94, 62, 102), fill="#263F55")
    return im


def main():
    root = Path(__file__).resolve().parents[1] / "src" / "genmedia" / "data" / "assets" / "demo"
    (root / "characters").mkdir(parents=True, exist_ok=True)
    (root / "backgrounds").mkdir(exist_ok=True)
    assets = []
    for label, obj in zip("ABCDEF", ["apple", "balloon", "cloud", "diamond", "egg", "fish"]):
        name = f"characters/{obj}.png"
        draw_object(obj).save(root / name)
        assets.append(dict(id=obj, kind="character", path=name, label=label, object=obj,
            plural=(obj+"s" if obj != "fish" else "fish"),
            description=f"Simple geometric {obj}, cheerful educational fixture",
            tags=["geometric", "original fixture"], provenance="Generated by scripts/build_demo.py"))
    for name, top, bottom in [("sky", (207,233,251), (169,210,191)),
                              ("studio", (245,222,200), (232,198,203)),
                              ("water", (192,227,233), (99,164,192))]:
        image = Image.new("RGB", (640, 360))
        d = ImageDraw.Draw(image)
        for y in range(360):
            a = y/359
            color = tuple(round(c*(1-a)+b*a) for c, b in zip(top, bottom))
            d.line((0,y,639,y), fill=color)
        d.ellipse((-80, 265, 730, 550), fill=bottom)
        image.save(root / f"backgrounds/{name}.png")
        assets.append(dict(id=name, kind="background", path=f"backgrounds/{name}.png",
            description=f"Simple {name} backdrop", tags=[name], provenance="Generated by scripts/build_demo.py"))
    (root / "manifest.json").write_text(json.dumps({"version":1, "root":".", "assets":assets}, indent=2)+"\n", encoding="utf-8")
    print(f"Created {len(assets)} original demo assets at {root}")

if __name__ == "__main__":
    main()
